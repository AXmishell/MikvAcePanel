func TestDDLForSchemas(t *testing.T) {
	for _, d := range []Dialect{SQLiteDialect{}, PostgresDialect{}, MySQLDialect{}} {
		for _, table := range schema.Tables {
			ddl := d.CreateTable(table)
			if !strings.Contains(ddl, "CREATE TABLE IF NOT EXISTS") {
				t.Fatalf("%s %s: %s", d.Name(), table.Name, ddl)
			}
			if !strings.Contains(ddl, table.Name) {
				t.Fatalf("%s %s: table name missing", d.Name(), table.Name)
			}
		}
	}
}

func TestColumnDDL(t *testing.T) {
	id := schema.Column{Name: "id", Kind: schema.Int64, PK: true, Auto: true}
	text := schema.Column{Name: "name", Kind: schema.String, Size: 32, NotNull: true, Default: "x"}
	jsonCol := schema.Column{Name: "data", Kind: schema.JSON, NotNull: true, Default: "[]"}

	sq := SQLiteDialect{}
	if got := sq.ColumnDDL(id); !strings.Contains(got, "INTEGER PRIMARY KEY AUTOINCREMENT") {
		t.Fatalf("sqlite id: %s", got)
	}
	if got := sq.ColumnDDL(text); got != `"name" VARCHAR(32) NOT NULL DEFAULT 'x'` {
		t.Fatalf("sqlite text: %s", got)
	}

	pg := PostgresDialect{}
	if got := pg.ColumnDDL(id); !strings.Contains(got, "GENERATED BY DEFAULT AS IDENTITY") {
		t.Fatalf("pg id: %s", got)
	}
	if got := pg.ColumnDDL(jsonCol); !strings.Contains(got, "DEFAULT '[]'") {
		t.Fatalf("pg json: %s", got)
	}

	my := MySQLDialect{}
	if got := my.ColumnDDL(id); !strings.Contains(got, "AUTO_INCREMENT") {
		t.Fatalf("mysql id: %s", got)
	}
	if got := my.ColumnDDL(jsonCol); !strings.Contains(got, "DEFAULT ('[]')") {
		t.Fatalf("mysql json default: %s", got)
	}
	if got := my.TableSuffix(); !strings.Contains(got, "utf8mb4_bin") {
		t.Fatalf("mysql suffix: %s", got)
	}
}

func TestDMLFragments(t *testing.T) {
	cols := []string{"setting_key", "value"}
	if got := (SQLiteDialect{}).InsertIgnore("settings", cols, []string{"setting_key"}); !strings.Contains(got, "INSERT OR IGNORE") {
		t.Fatalf("sqlite ignore: %s", got)
	}
	if got := (PostgresDialect{}).InsertIgnore("settings", cols, []string{"setting_key"}); !strings.Contains(got, "ON CONFLICT") {
		t.Fatalf("pg ignore: %s", got)
	}
	if got := (MySQLDialect{}).InsertIgnore("settings", cols, []string{"setting_key"}); !strings.Contains(got, "ON DUPLICATE KEY UPDATE") {
		t.Fatalf("mysql ignore: %s", got)
	}
	if got := (PostgresDialect{}).Upsert("settings", cols, []string{"setting_key"}, []string{"value"}); !strings.Contains(got, "excluded") {
		t.Fatalf("pg upsert: %s", got)
	}
	if got := (MySQLDialect{}).Upsert("settings", cols, []string{"setting_key"}, []string{"value"}); !strings.Contains(got, "VALUES") {
		t.Fatalf("mysql upsert: %s", got)
	}
	if got := (MySQLDialect{}).CreateIndex("nodes", schema.Index{Name: "i", Columns: []string{"name"}}); strings.Contains(got, "IF NOT EXISTS") {
		t.Fatalf("mysql index should not use IF NOT EXISTS: %s", got)
	}
}
