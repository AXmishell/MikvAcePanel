package dialect

import (
	"context"
	"database/sql"
	"strings"

	"github.com/axmishell/mikvacepanel/internal/store/schema"
)

// PostgresDialect targets PostgreSQL 18 (and older releases with the same
// SQL surface). The pgx driver is used through database/sql.
type PostgresDialect struct{}

func (PostgresDialect) Name() string       { return Postgres }
func (PostgresDialect) DriverName() string { return "pgx" }
func (PostgresDialect) Rebind(q string) string {
	return rebindToDollar(q)
}
func (PostgresDialect) Quote(ident string) string {
	return `"` + strings.ReplaceAll(ident, `"`, `""`) + `"`
}
func (PostgresDialect) IsUniqueViolation(err error) bool {
	if err == nil {
		return false
	}
	if sqlStateOf(err) == "23505" {
		return true
	}
	return strings.Contains(strings.ToLower(err.Error()), "duplicate key value violates unique constraint")
}
func (PostgresDialect) IsRetryable(err error) bool {
	if err == nil {
		return false
	}
	switch sqlStateOf(err) {
	case "40001", "40P01", "57P01", "57P02", "57P03":
		return true
	}
	msg := strings.ToLower(err.Error())
	return containsAny(msg, "connection refused", "connection reset", "bad connection", "server closed the connection")
}

func (d PostgresDialect) ColumnDDL(c schema.Column) string {
	name := quoteIdent(d, c.Name)
	if c.Auto && c.PK {
		return name + " BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}
	parts := []string{name, ColumnType(d, c)}
	if c.NotNull {
		parts = append(parts, "NOT NULL")
	}
	if c.Default != nil {
		parts = append(parts, "DEFAULT "+sqlLiteral(c.Default))
	}
	if c.Unique {
		parts = append(parts, "UNIQUE")
	}
	if c.PK {
		parts = append(parts, "PRIMARY KEY")
	}
	return strings.Join(parts, " ")
}

func (PostgresDialect) TableSuffix() string { return "" }
func (d PostgresDialect) CreateTable(t schema.Table) string {
	return createTable(d, t)
}
func (d PostgresDialect) CreateIndex(table string, ix schema.Index) string {
	return createIndex(d, table, ix)
}
func (d PostgresDialect) AddColumn(table string, c schema.Column) string {
	return addColumn(d, table, c)
}
func (d PostgresDialect) InsertIgnore(table string, cols, conflict []string) string {
	return insertIgnoreSQL(d, table, cols, conflict)
}
func (d PostgresDialect) Upsert(table string, cols, conflict, updates []string) string {
	return upsertSQL(d, table, cols, conflict, updates)
}
func (d PostgresDialect) HasTable(ctx context.Context, q Querier, table string) (bool, error) {
	return hasTable(ctx, q, d, table)
}
func (d PostgresDialect) HasColumn(ctx context.Context, q Querier, table, column string) (bool, error) {
	return hasColumn(ctx, q, d, table, column)
}
func (d PostgresDialect) HasIndex(ctx context.Context, q Querier, table, index string) (bool, error) {
	return hasIndex(ctx, q, d, table, index)
}
func (d PostgresDialect) AcquireMigrationLock(ctx context.Context, db *sql.DB) (func(), error) {
	return acquireLock(ctx, db, d)
}
